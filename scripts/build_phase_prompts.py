#!/usr/bin/env python3
"""Embed the batch specs into each group prompt in docs/prompts/PHASE_<n>.md.

Each fenced ```text prompt names its batches ("Group P2.1 = batches 2.1 to 2.5"). This script
copies the matching specs from docs/prompts/paste-ready/<id>-*.md (after slim_prompts.py) to the
end of that prompt, under the marker line, so one paste is the whole prompt. Re-run it whenever a
spec changes (for example after count fixes). Idempotent.

Usage: python scripts/build_phase_prompts.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SPECS = ROOT / "docs" / "prompts" / "paste-ready"
MARK = "=== BATCH SPECS (generated by scripts/build_phase_prompts.py; do not open docs/prompts/paste-ready/) ==="
GROUP = re.compile(
    r"Group P\d\.\d = batch(?:es)? (\d)\.(\d+)(?: (?:to|and) \d\.(\d+))?"
)


def spec_text(phase: str, n: int) -> str:
    files = sorted(SPECS.glob(f"{phase}.{n:02d}-*.md"))
    if len(files) != 1:
        raise SystemExit(f"expected one spec for {phase}.{n}, found {len(files)}")
    lines = files[0].read_text(encoding="utf-8").splitlines()
    lines = [ln for ln in lines if not ln.startswith("> Spec only")]
    out = []
    for ln in lines:
        if ln.startswith("## "):
            ln = "#### " + ln[3:]
        elif ln.startswith("# "):
            ln = "### " + ln[2:]
        out.append(ln.rstrip())
    return "\n".join(out).strip()


def rebuild_block(m: re.Match) -> str:
    body = m.group(1).split(MARK)[0].rstrip()
    g = GROUP.search(body)
    if not g:
        return m.group(0)
    phase, a = g.group(1), int(g.group(2))
    b = int(g.group(3)) if g.group(3) else a
    specs = "\n\n".join(spec_text(phase, n) for n in range(a, b + 1))
    return f"```text\n{body}\n\n{MARK}\n\n{specs}\n```"


def main() -> int:
    for f in sorted((ROOT / "docs" / "prompts").glob("PHASE_*.md")):
        t = f.read_text(encoding="utf-8")
        new = re.sub(r"```text\n(.*?)\n```", rebuild_block, t, flags=re.S)
        f.write_text(new, encoding="utf-8")
        print(f"{f.name}: {len(t.encode())} -> {len(new.encode())} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
